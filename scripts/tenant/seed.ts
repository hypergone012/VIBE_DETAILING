#!/usr/bin/env tsx
/**
 * pnpm seed:build — writes supabase/seed.sql from the demo studios in tenants/
 * (business.json with "demo": true). The seed uses the same admin_publish_tenant as
 * the pipeline, so seed and pipeline cannot drift. Media paths are content-addressed
 * and match what `pnpm tenant:publish` uploads (`pnpm demo:media` after a reset).
 *
 * Contents: demo studios (preview), local-only owner accounts, demo bookings and
 * payments relative to the time of `supabase db reset`.
 */
import { createHash } from 'node:crypto';
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { prepareMedia } from './images.ts';
import { listTenantSlugs, loadBusiness, ROOT } from './load.ts';
import { normalizeBusiness, type Business, type MediaPaths } from './schema.ts';

/** Deterministic UUID from a string (stable ids for demo rows). */
export function stableUuid(input: string): string {
  const h = createHash('sha256').update(input).digest('hex');
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-4${h.slice(13, 16)}-a${h.slice(17, 20)}-${h.slice(20, 32)}`;
}

/** Local-only demo owner password (documented in SETUP.md; never used in production). */
export const demoOwnerPassword = (slug: string) => `demo-${slug}-local`;

interface DemoBooking {
  service: string;
  day: number;
  time: string;
  name: string;
  phone: string;
  car: string;
  status: 'confirmed' | 'arrived' | 'done' | 'cancelled' | 'no_show';
  paid?: number;
}

